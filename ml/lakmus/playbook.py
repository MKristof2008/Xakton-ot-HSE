"""Плейбук: по какому алгоритму искать признаки фейка.

Модель не должна «просто посмотреть» на текст. Ей даётся чек-лист под
конкретный тип материала и конкретную тему:

  * что проверить в первую очередь;
  * какие признаки говорят о подделке;
  * какие признаки говорят о подлинности;
  * что доказательством не считается;
  * что делать, если данных нет.

Это и есть тот самый «алгоритм, по которому вычисляется фейк/не фейк».
Он одинаков для всех тарифов и прогонов, а модель только заполняет его
по факту — поэтому ответ не зависит от настроения модели.

Почему по темам, а не один общий список: у экономики и у медицины разные
признаки лжи. «ЦБ запретил наличные» опровергается пресс-релизом ЦБ, а
«лекарство от рака» — отсутствием регистрации препарата. Один промпт на
всё заставлял модель смешивать критерии.

Типы материалов:

  text  — сообщение, пост, пересказ новости;
  link  — ссылка на публикацию (текст берётся со страницы);
  image — скриншот, фото, картинка;
  video — ролик.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional


@dataclass
class Plan:
    """Чек-лист проверки для одного типа материала и темы."""

    kind: str
    title: str
    #: Что проверить, по порядку.
    steps: list[str] = field(default_factory=list)
    #: Признаки подделки.
    fake_signals: list[str] = field(default_factory=list)
    #: Признаки подлинности.
    real_signals: list[str] = field(default_factory=list)
    #: Что нельзя считать доказательством.
    not_proof: list[str] = field(default_factory=list)
    #: Правила вывода: как трактовать нехватку данных.
    rules: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, object]:
        return {
            "kind": self.kind,
            "title": self.title,
            "steps": self.steps,
            "fake_signals": self.fake_signals,
            "real_signals": self.real_signals,
            "not_proof": self.not_proof,
            "rules": self.rules,
        }

    def as_prompt(self) -> str:
        """Текст для модели: чек-лист в виде инструкции."""
        parts = [f"АЛГОРИТМ ПРОВЕРКИ ({self.title}):"]
        if self.steps:
            parts.append("Шаги:")
            parts.extend(f"  {i}. {s}" for i, s in enumerate(self.steps, 1))
        if self.fake_signals:
            parts.append("Признаки подделки:")
            parts.extend(f"  - {s}" for s in self.fake_signals)
        if self.real_signals:
            parts.append("Признаки подлинности:")
            parts.extend(f"  - {s}" for s in self.real_signals)
        if self.not_proof:
            parts.append("НЕ считается доказательством:")
            parts.extend(f"  - {s}" for s in self.not_proof)
        if self.rules:
            parts.append("Правила вывода:")
            parts.extend(f"  - {s}" for s in self.rules)
        return "\n".join(parts)


