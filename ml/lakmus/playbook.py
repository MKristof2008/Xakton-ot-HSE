def for_material(kind: str, tag_key: Optional[str] = None) -> Plan:
    """Собрать чек-лист под тип материала и тему."""
    kind = (kind or "text").strip().lower()
    if kind == "link":
        kind = "text"

    if kind in ("image", "video"):
        return Plan(
            kind=kind,
            title="фото" if kind == "image" else "видео",
            steps=list(_MEDIA_STEPS[kind]),
            fake_signals=list(_MEDIA_FAKE),
            real_signals=list(_MEDIA_REAL),
            not_proof=list(_MEDIA_NOT_PROOF),
            rules=list(_MEDIA_RULES),
        )

    topic = _TOPIC_TEXT.get((tag_key or "").strip().lower(), _TOPIC_TEXT_DEFAULT)
    return Plan(
        kind="text",
        title=f"текст, тема: {tag_key or 'не определена'}",
        steps=list(_TEXT_COMMON_STEPS) + list(topic.get("steps", [])),
        fake_signals=list(topic.get("fake_signals", [])),
        real_signals=list(topic.get("real_signals", [])),
        not_proof=list(_TEXT_COMMON_NOT_PROOF),
        rules=list(_TEXT_COMMON_RULES),
    )


def all_kinds() -> list[str]:
    return ["text", "link", "image", "video"]
