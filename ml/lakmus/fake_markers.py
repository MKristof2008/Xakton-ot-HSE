"""Признаки вирусного фейка в самом тексте — без поиска и без модели.

Зачем. Если ключа поиска нет или тема не покрыта базой, проверка честно
отвечает «непонятно». Но часть выдумок выдаёт себя самим текстом: «СРОЧНО,
перешлите всем», «с 1 января всех обязали», абсолютная категоричность,
отсутствие атрибуции, обещания мгновенного эффекта.

Здесь собран словарь таких признаков — не «список запрещённых слов», а
маркеры жанра. Каждый маркер объясним и имеет вес. Работает одинаково на
всех тарифах и не зависит от сети, поэтому результат воспроизводим.

Ключевое правило: **эти признаки не ставят вердикт сами**. Они дают
основание сказать «похоже на вирусную выдумку» и объяснить почему, но
окончательный вердикт остаётся за правилами темы. Иначе любое сообщение
с восклицательным знаком объявлялось бы фейком.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any


@dataclass
class Marker:
    """Один признак жанра."""

    key: str
    title: str
    weight: float
    reason: str
    #: Что нашлось в тексте — для объяснения человеку.
    evidence: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "title": self.title,
            "weight": round(self.weight, 3),
            "reason": self.reason,
            "evidence": self.evidence[:4],
        }


#: Маркеры жанра. Вес — вклад в «похоже на выдумку», не приговор.
