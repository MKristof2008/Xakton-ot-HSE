def _compile() -> list[tuple[str, str, float, str, list[re.Pattern[str]]]]:
    return [
        (key, title, weight, reason, [re.compile(p, re.I) for p in patterns])
        for key, title, weight, reason, patterns in _MARKERS
    ]


_COMPILED = _compile()


def find_markers(text: str) -> list[Marker]:
    """Найти признаки жанра в тексте. Пустой список — признаков нет."""
    if not (text or "").strip():
        return []
    out: list[Marker] = []
    for key, title, weight, reason, patterns in _COMPILED:
        evidence: list[str] = []
        for pattern in patterns:
            for match in pattern.finditer(text):
                fragment = match.group(0).strip()
                if fragment and fragment.lower() not in [
                    e.lower() for e in evidence
                ]:
                    evidence.append(fragment)
        if evidence:
            out.append(Marker(key, title, weight, reason, evidence[:4]))
    return out


def score(markers: list[Marker]) -> float:
    """Суммарный вес признаков, но с насыщением.

    Много однотипных маркеров не должны складываться в приговор: берём
    корень из суммы, чтобы три признака весили больше одного, но не втрое.
    Максимум — 0.6: сами по себе маркеры не дают вердикт «фейк».
    """
    if not markers:
        return 0.0
    total = sum(m.weight for m in markers)
    return min(0.6, round(total ** 0.5 * 0.55, 3))


def explain(markers: list[Marker]) -> str:
    """Короткое объяснение для человека."""
    if not markers:
        return ""
    titles = ", ".join(m.title.lower() for m in markers[:3])
    return f"В тексте есть признаки вирусной выдумки: {titles}."


def as_signal(markers: list[Marker]) -> dict[str, Any]:
    """Представление для API: что нашли и насколько это весомо."""
    return {
        "score": score(markers),
        "summary": explain(markers),
        "markers": [m.as_dict() for m in markers],
    }
