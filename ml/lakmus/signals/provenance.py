def _all_text(meta: dict[str, Any]) -> list[tuple[str, str]]:
    """Пары (источник, значение) для поиска маркеров."""
    pairs: list[tuple[str, str]] = []
    for key, value in meta["text"].items():
        if isinstance(value, str) and value:
            pairs.append((f"png:{key}", value))
    for key, value in meta["exif"].items():
        if isinstance(value, str) and value:
            pairs.append((f"exif:{key}", value))
    if meta["xmp"]:
        pairs.append(("xmp", str(meta["xmp"])))
    generator = meta["c2pa"].get("claim_generator")
    if generator:
        pairs.append(("c2pa:claim_generator", str(generator)))
    return pairs


def _find_markers(
    pairs: list[tuple[str, str]], markers: tuple[str, ...]
) -> list[dict[str, str]]:
    hits: list[dict[str, str]] = []
    for source, value in pairs:
        low = value.lower()
        for marker in markers:
            if marker in low:
                hits.append({"source": source, "marker": marker, "value": value[:200]})
                break
    return hits


def _camera_label(exif: dict[str, Any]) -> Optional[str]:
    make = exif.get("Make")
    model = exif.get("Model")
    if not isinstance(make, str) or not make:
        return None
    if isinstance(model, str) and model:
        if model.lower().startswith(make.lower()):
            return model
        return f"{make} {model}"
    return make


def _build_details(meta: dict[str, Any], pairs: list[tuple[str, str]]) -> dict[str, Any]:
    exif = meta["exif"]
    gps = dict(meta["gps"])
    gps_out: dict[str, Any] = {}
    for key in ("Latitude", "Longitude"):
        degrees = _dms_to_degrees(gps.get(key))
        if degrees is not None:
            gps_out[key.lower()] = degrees
    for key in ("LatitudeRef", "LongitudeRef"):
        if gps.get(key):
            gps_out[key.lower() + "_ref"] = gps[key]
    camera = _camera_label(exif)
    datetime_value = (
        exif.get("DateTimeOriginal") or exif.get("DateTime") or exif.get("DateTimeDigitized")
    )
    return {
        "format": meta["format"],
        "has_metadata": meta["has_metadata"],
        "text_keys": sorted(meta["text"])[:20],
        "exif_tags": sorted(exif)[:20],
        "software": exif.get("Software") if isinstance(exif.get("Software"), str) else None,
        "camera": camera,
        "datetime": datetime_value if isinstance(datetime_value, str) else None,
        "gps": gps_out,
        "xmp_present": bool(meta["xmp"]),
        "c2pa": dict(meta["c2pa"]),
        "generators": _find_markers(pairs, GENERATOR_MARKERS),
        "editors": _find_markers(pairs, EDITOR_MARKERS),
        "signature_verified": False,
    }


class MetadataSignal(BaseSignal):
    """I1: метаданные файла — самый дешёвый сигнал происхождения."""

    id = "metadata"
    name = "Метаданные"
    stage = Stage.provenance
    timeout_s = 8.0

    async def run(self, ctx: CheckContext):
        if ctx.input.type != InputType.image:
            return self.unavailable("сигнал работает только с изображениями")
        data = ctx.data
        if not data:
            return self.unavailable("нет байтов изображения на входе")
        meta = ctx.cache.get("metadata")
        if not isinstance(meta, dict) or "c2pa" not in meta:
            try:
                meta = parse_metadata(data)
            except Exception as exc:  # parse_metadata не бросает, но контракт важнее
                return self.unavailable(f"разбор метаданных не удался: {type(exc).__name__}")
            ctx.remember("metadata", meta)
        pairs = _all_text(meta)
        details = _build_details(meta, pairs)
        return self._judge(meta, pairs, details)

    def _judge(
        self,
        meta: dict[str, Any],
        pairs: list[tuple[str, str]],
        details: dict[str, Any],
    ):
        generators = details["generators"]
        editors = details["editors"]
        c2pa = meta["c2pa"]
        camera = details["camera"]
        datetime_value = details["datetime"]

        if generators:
            marks = ", ".join(sorted({hit["marker"] for hit in generators}))[:120]
            summary = (
                f"В метаданных есть следы генерации ({marks}). "
                "Скорее всего изображение создано нейросетью."
            )
            if c2pa.get("present"):
                summary = (
                    f"В метаданных есть следы генерации ({marks}), хотя файл и подписан C2PA. "
                    "Подпись удостоверяет автора, а не реальность кадра."
                )
            return make_result(
                self, Verdict.supports_fake, 0.7, 0.9, summary, details
            )

        if c2pa.get("present") and c2pa.get("has_claim"):
            summary = (
                "Найдена подпись происхождения C2PA: файл подписан инструментом создания. "
                "Это сильный признак исходного файла, но подпись подтверждает автора, а не правдивость кадра."
            )
            details["note"] = "криптографическая проверка подписи на stdlib не выполнялась"
            return make_result(
                self, Verdict.supports_real, 0.9, 0.95, summary, details
            )

        if camera and datetime_value:
            summary = (
                f"Метаданные камеры ({camera}) и дата съёмки {datetime_value} на месте. "
                "Похоже на исходный снимок, но метаданные несложно подделать."
            )
            return make_result(self, Verdict.supports_real, 0.5, 0.6, summary, details)

        if camera:
            summary = (
                f"В метаданных указана камера ({camera}), но даты съёмки нет. "
                "Слабый признак исходного файла."
            )
            return make_result(self, Verdict.supports_real, 0.3, 0.5, summary, details)

        if editors:
            marks = ", ".join(sorted({hit["marker"] for hit in editors}))[:120]
            details["editor_only"] = True
            summary = (
                f"Метаданные содержат только следы редактора ({marks}). "
                "Это не доказывает подделку: так обрабатывают и настоящие фотографии."
            )
            return make_result(self, Verdict.neutral, 0.2, 0.4, summary, details)

        if not meta["has_metadata"]:
            details["no_metadata"] = True
            summary = (
                "Метаданных нет: соцсети и мессенджеры стирают их при загрузке. "
                "Отсутствие метаданных ничего не доказывает."
            )
            return make_result(self, Verdict.neutral, 0.0, 0.2, summary, details)

        summary = (
            "Метаданные есть, но следов камеры, редактора или генерации в них нет. "
            "Для вывода этого мало."
        )
        return make_result(self, Verdict.neutral, 0.1, 0.3, summary, details)
