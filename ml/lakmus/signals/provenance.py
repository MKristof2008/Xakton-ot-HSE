"""Сигнал I1 «Метаданные»: происхождение файла (раздел 6.3 ТЗ).

Разбор только на stdlib: PNG-чанки (tEXt/iTXt/zTXt/eXIf/caBX), JPEG APP1
(Exif/TIFF IFD, XMP-пакет) и APP11 (JUMBF/C2PA). Публичная функция
parse_metadata(data) не зависит от контекста проверки — её можно
тестировать отдельно от сигнала.

Ограничение честно фиксируется в details: криптографическая проверка
подписи C2PA на stdlib не выполняется, проверяется структура манифеста.
"""

from __future__ import annotations

import zlib
from typing import Any, Iterator, Optional

from ..context import CheckContext
from ..schemas import InputType, Stage, Verdict
from .base import BaseSignal, make_result

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
JPEG_SOI = b"\xff\xd8"
EXIF_PREFIX = b"Exif\x00\x00"
XMP_JPEG_PREFIX = b"http://ns.adobe.com/xap/1.0/"
XMP_EXT_PREFIX = b"http://ns.adobe.com/xmp/extension/"

_MAX_INFLATE = 1 << 20   # предел распаковки текстового чанка (анти-бомба)
_MAX_IFD_ENTRIES = 512
_MAX_TEXT_VALUE = 8192

# Следы генерации в метаданных. Сравнение — по подстроке в нижнем регистре.
GENERATOR_MARKERS: tuple[str, ...] = (
    "stable diffusion", "stablediffusion", "sd-webui", "automatic1111",
    "comfyui", "invokeai", "novelai", "midjourney", "dall·e", "dall-e",
    "dalle", "adobe firefly", "firefly", "sdxl", "flux.1", "kandinsky",
    "neuralsampler", "generated by", "generated with", "ai-generated",
    "ai generated", "сгенерировано", "нейросеть", "image generator",
)

# Следы редактора: сами по себе ничего не доказывают.
EDITOR_MARKERS: tuple[str, ...] = (
    "photoshop", "lightroom", "gimp", "affinity photo", "camera raw",
    "snapseed", "picsart", "canva", "pixlr", "paint.net", "facetune",
)

_IFD_TAGS: dict[int, str] = {
    0x010E: "ImageDescription",
    0x010F: "Make",
    0x0110: "Model",
    0x0112: "Orientation",
    0x0131: "Software",
    0x0132: "DateTime",
    0x013B: "Artist",
    0x8298: "Copyright",
    0x9003: "DateTimeOriginal",
    0x9004: "DateTimeDigitized",
    0xA420: "ImageUniqueID",
}

_GPS_TAGS: dict[int, str] = {
    0x0000: "VersionID",
    0x0001: "LatitudeRef",
    0x0002: "Latitude",
    0x0003: "LongitudeRef",
    0x0004: "Longitude",
    0x0005: "AltitudeRef",
    0x0006: "Altitude",
}

_TYPE_SIZE: dict[int, int] = {
    1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 6: 1, 7: 1, 8: 2, 9: 4, 10: 8, 11: 4, 12: 8,
}


# --------------------------------------------------------------------------
# низкоуровневый разбор
# --------------------------------------------------------------------------


def _empty_meta() -> dict[str, Any]:
    return {
        "format": "unknown",
        "text": {},          # текстовые чанки PNG: ключ -> значение
        "exif": {},          # понятные имена тегов TIFF/Exif
        "gps": {},
        "xmp": None,
        "c2pa": {
            "present": False,
            "has_claim": False,
            "signature_present": False,
            "claim_generator": None,
            "verified": False,
        },
        "has_metadata": False,
    }


def _inflate(payload: bytes) -> Optional[bytes]:
    """Распаковка с ограничением размера: битые и «бомбы» не ломают проверку."""
    try:
        stream = zlib.decompressobj()
        out = stream.decompress(payload, _MAX_INFLATE)
        return out
    except zlib.error:
        return None


def _iter_png_chunks(data: bytes) -> Iterator[tuple[bytes, bytes]]:
    pos = len(PNG_SIGNATURE)
    total = len(data)
    while pos + 8 <= total:
        length = int.from_bytes(data[pos:pos + 4], "big")
        ctype = data[pos + 4:pos + 8]
        start = pos + 8
        end = start + length
        if end + 4 > total:
            break
        yield ctype, data[start:end]
        pos = end + 4
        if ctype == b"IEND":
            break


def _decode_value(buf: bytes, typ: int, count: int, raw: bytes, endian: str):
    size = _TYPE_SIZE.get(typ)
    if size is None or count <= 0 or count > 4096:
        return None
    total = size * count
    if total <= 4:
        chunk = raw[:total]
    else:
        offset = int.from_bytes(raw, endian)
        if offset <= 0 or offset + total > len(buf):
            return None
        chunk = buf[offset:offset + total]
    if typ == 2:  # ASCII
        text = chunk.split(b"\x00", 1)[0].decode("utf-8", "replace").strip()
        return text[:_MAX_TEXT_VALUE]
    if typ in (1, 7):
        return list(chunk)
    if typ in (3, 4, 8, 9):
        signed = typ in (8, 9)
        return [
            int.from_bytes(chunk[i:i + size], endian, signed=signed)
            for i in range(0, total, size)
        ]
    if typ in (5, 10):
        signed = typ == 10
        out: list[float] = []
        for i in range(0, total, 8):
            num = int.from_bytes(chunk[i:i + 4], endian, signed=signed)
            den = int.from_bytes(chunk[i + 4:i + 8], endian, signed=signed)
            out.append(num / den if den else 0.0)
        return out
    return None


def _read_ifd(
    buf: bytes,
    offset: int,
    endian: str,
    out: dict[str, Any],
    gps: dict[str, Any],
    depth: int = 0,
) -> None:
    if depth > 2 or offset < 8 or offset + 2 > len(buf):
        return
    count = int.from_bytes(buf[offset:offset + 2], endian)
    if count > _MAX_IFD_ENTRIES:
        return
    pos = offset + 2
    for _ in range(count):
        if pos + 12 > len(buf):
            return
        tag = int.from_bytes(buf[pos:pos + 2], endian)
        typ = int.from_bytes(buf[pos + 2:pos + 4], endian)
        cnt = int.from_bytes(buf[pos + 4:pos + 8], endian)
        raw = buf[pos + 8:pos + 12]
        pos += 12
        if tag in (0x8769, 0x8825) and typ in (4, 13):
            _read_ifd(buf, int.from_bytes(raw, endian), endian, out, gps, depth + 1)
            continue
        name = _IFD_TAGS.get(tag)
        gps_name = _GPS_TAGS.get(tag) if depth > 0 else None
        if name is None and gps_name is None:
            continue
        value = _decode_value(buf, typ, cnt, raw, endian)
        if value is None or value == "" or value == []:
            continue
        if gps_name is not None:
            gps[gps_name] = value
        elif name is not None:
            out[name] = value


def _parse_tiff(buf: bytes) -> tuple[dict[str, Any], dict[str, Any]]:
    """TIFF/Exif IFD → (теги, GPS). Ошибка означает «метаданных нет»."""
    if buf.startswith(EXIF_PREFIX):
        buf = buf[len(EXIF_PREFIX):]
    if len(buf) < 8:
        return {}, {}
    if buf[:2] == b"II":
        endian = "little"
    elif buf[:2] == b"MM":
        endian = "big"
    else:
        return {}, {}
    if int.from_bytes(buf[2:4], endian) != 42:
        return {}, {}
    tags: dict[str, Any] = {}
    gps: dict[str, Any] = {}
    _read_ifd(buf, int.from_bytes(buf[4:8], endian), endian, tags, gps)
    return tags, gps


def _dms_to_degrees(value: Any) -> Optional[float]:
    if not isinstance(value, list) or not value:
        return None
    parts = [float(v) for v in value[:3] if isinstance(v, (int, float))]
    if not parts:
        return None
    degrees = parts[0]
    if len(parts) > 1:
        degrees += parts[1] / 60.0
    if len(parts) > 2:
        degrees += parts[2] / 3600.0
    return round(degrees, 6)


def _scan_c2pa(payload: bytes, c2pa: dict[str, Any]) -> None:
    low = payload.lower()
    if b"jumb" not in low and b"c2pa" not in low and b"c2pa." not in low:
        return
    c2pa["present"] = True
    if b"c2pa.claim" in low or b"c2pa.assertions" in low:
        c2pa["has_claim"] = True
    if b"c2pa.signature" in low or b"cose" in low or b"signature_info" in low:
        c2pa["signature_present"] = True
    marker = b"c2pa.claim_generator"
    if marker in low:
        idx = low.index(marker)
        tail = payload[idx:idx + 200]
        c2pa["claim_generator"] = tail.decode("utf-8", "replace")


def _parse_png(data: bytes, meta: dict[str, Any]) -> None:
    meta["format"] = "png"
    exif_blob: Optional[bytes] = None
    for ctype, payload in _iter_png_chunks(data):
        if ctype in (b"tEXt", b"zTXt", b"iTXt", b"eXIf", b"caBX"):
            meta["has_metadata"] = True
        if ctype == b"tEXt":
            key, _, value = payload.partition(b"\x00")
            meta["text"][key.decode("latin-1", "replace")] = (
                value.decode("latin-1", "replace")[:_MAX_TEXT_VALUE]
            )
        elif ctype == b"zTXt":
            key, _, rest = payload.partition(b"\x00")
            body = _inflate(rest[1:]) if len(rest) > 1 else None
            meta["text"][key.decode("latin-1", "replace")] = (
                body.decode("latin-1", "replace")[:_MAX_TEXT_VALUE] if body else ""
            )
        elif ctype == b"iTXt":
            key, _, rest = payload.partition(b"\x00")
            if len(rest) >= 2:
                compressed = rest[0] == 1
                parts = rest[2:].split(b"\x00", 2)
                body = parts[2] if len(parts) == 3 else rest[2:]
                if compressed:
                    body = _inflate(body) or b""
                value = body.decode("utf-8", "replace")[:_MAX_TEXT_VALUE]
                key_text = key.decode("latin-1", "replace")
                meta["text"][key_text] = value
                if "xml" in key_text.lower() or "xmp" in key_text.lower():
                    meta["xmp"] = value
        elif ctype == b"eXIf":
            exif_blob = payload
        elif ctype == b"caBX":
            _scan_c2pa(payload, meta["c2pa"])
    if exif_blob:
        tags, gps = _parse_tiff(exif_blob)
        meta["exif"].update(tags)
        meta["gps"].update(gps)
    for value in meta["text"].values():
        if value.lstrip().startswith("<") and "xmpmeta" in value.lower():
            meta["xmp"] = value
            break


def _jpeg_segments(data: bytes) -> Iterator[tuple[int, bytes]]:
    pos = 2
    total = len(data)
    while pos + 4 <= total:
        if data[pos] != 0xFF:
            pos += 1
            continue
        marker = data[pos + 1]
        if marker == 0xFF:
            pos += 1
            continue
        if marker in (0x01,) or 0xD0 <= marker <= 0xD9:
            pos += 2
            if marker == 0xD9:  # EOI — дальше только сжатые данные
                return
            continue
        length = int.from_bytes(data[pos + 2:pos + 4], "big")
        if length < 2:
            return
        end = pos + 2 + length
        if end > total:
            return
        yield marker, data[pos + 4:end]
        if marker == 0xDA:  # SOS — дальше энтропийно-кодированные данные
            return
        pos = end


def _parse_jpeg(data: bytes, meta: dict[str, Any]) -> None:
    meta["format"] = "jpeg"
    for marker, payload in _jpeg_segments(data):
        if marker == 0xE1:  # APP1: Exif или XMP
            meta["has_metadata"] = True
            if payload.startswith(EXIF_PREFIX):
                tags, gps = _parse_tiff(payload)
                meta["exif"].update(tags)
                meta["gps"].update(gps)
            elif payload.startswith(XMP_JPEG_PREFIX):
                xml = payload[len(XMP_JPEG_PREFIX):].lstrip(b"\x00")
                meta["xmp"] = xml.decode("utf-8", "replace")[:_MAX_TEXT_VALUE * 4]
            elif payload.startswith(XMP_EXT_PREFIX):
                meta["text"]["XMP:extension"] = "да"
        elif marker == 0xEB:  # APP11: JUMBF / C2PA
            before = meta["c2pa"]["present"]
            _scan_c2pa(payload, meta["c2pa"])
            if meta["c2pa"]["present"] and not before:
                meta["has_metadata"] = True
        elif marker == 0xED:  # APP13: Photoshop IRB / IPTC
            if b"Photoshop" in payload:
                meta["has_metadata"] = True
                meta["text"].setdefault("APP13:Photoshop", "да")


def parse_metadata(data: bytes) -> dict[str, Any]:
    """Разбирает метаданные PNG/JPEG. Никогда не бросает исключений.

    Возвращает словарь: format, text, exif, gps, xmp, c2pa, has_metadata.
    Неизвестный формат — format="unknown" и has_metadata=False.
    """
    meta = _empty_meta()
    try:
        if data and data.startswith(PNG_SIGNATURE):
            _parse_png(data, meta)
        elif data and data.startswith(JPEG_SOI):
            _parse_jpeg(data, meta)
    except Exception:  # разбор «мусора» не должен ломать проверку
        return _empty_meta()
    return meta


