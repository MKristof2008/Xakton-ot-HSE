def test_dhash_is_deterministic_and_discriminative():
    width, height, gray = decode_png_gray(png())
    first = dhash_hex(gray, width, height)
    second = dhash_hex(gray, width, height)
    assert len(first) == 16
    assert int(first, 16) <= 0xFFFFFFFFFFFFFFFF
    assert first == second
    assert hamming_hex(first, second) == 0

    other_w, other_h, other = decode_png_gray(png(rows=checker_rows(16, 16)))
    different = dhash_hex(other, other_w, other_h)
    assert hamming_hex(first, different) > 0


def test_phash_is_stable_for_same_image():
    width, height, gray = decode_png_gray(png())
    first = phash_hex(gray, width, height)
    assert len(first) == 16
    assert first == phash_hex(gray, width, height)
    assert hamming_hex(first, first) == 0


