async def test_source_search_matches_known_case(tmp_path):
    data = png()
    width, height, gray = decode_png_gray(data)
    phash = phash_hex(gray, width, height)
    dhash = dhash_hex(gray, width, height)

    cases_file = tmp_path / "known_cases.json"
    cases_file.write_text(json.dumps({"version": 1, "cases": [{
        "id": "demo-case",
        "phash": phash,
        "dhash": dhash,
        "date": "2019-04-01",
        "where": "Твиттер",
        "note": "тот же кадр в старом посте",
    }]}, ensure_ascii=False), encoding="utf-8")

    ctx = make_ctx(data, options={
        "known_cases_path": str(cases_file),
        "claimed_date": "2024-06-01",
    })
    result = await SourceSearchSignal().run(ctx)

    assert result.stage == Stage.sources
    assert result.verdict == Verdict.supports_fake
    assert result.reliability == pytest.approx(0.85)
    assert result.details["matches"][0]["distance"] == 0
    assert result.details["provenance"]
    assert result.details["provenance"][0]["where"] == "Твиттер"
    assert result.details["days_before_claimed"] >= 1


