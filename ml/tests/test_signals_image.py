async def test_all_image_signals_run_together(monkeypatch):
    def nothing(data, ctx):
        return None

    monkeypatch.setattr(manipulation, "DETECTORS", [nothing])
    data = png(texts={
        b"Software": b"Stable Diffusion",
        b"parameters": b"Steps: 30, Sampler: Euler a, CFG scale: 7",
    })
    ctx = make_ctx(data)

    signals = [
        MetadataSignal(),
        AIArtifactsSignal(),
        ManipulationSignal(),
        SourceSearchSignal(),
        ScreenshotSignal(),
    ]
    results, limits = await run_signals(signals, ctx)

    assert len(results) == 5
    by_id = {result.id: result for result in results}
    assert set(by_id) == {"metadata", "ai_artifacts", "manipulation", "source_search", "screenshot"}
    assert by_id["metadata"].verdict == Verdict.supports_fake
    assert by_id["ai_artifacts"].verdict == Verdict.supports_fake
    assert by_id["manipulation"].verdict == Verdict.unavailable
    assert by_id["source_search"].verdict == Verdict.neutral
    # Каждый результат сохраняет id и stage своего сигнала.
    for signal in signals:
        assert by_id[signal.id].stage == signal.stage
        assert 0.0 <= by_id[signal.id].strength <= 1.0
        assert by_id[signal.id].summary.strip()
    assert any("Следы монтажа" in item for item in limits)


def test_match_known_cases_respects_hamming_threshold():
    width, height, gray = decode_png_gray(png())
    phash = phash_hex(gray, width, height)
    near = f"{int(phash, 16) ^ 0x3:016x}"
    far = f"{int(phash, 16) ^ 0xFFFFFFFFFFFFFFFF:016x}"
    cases = [
        {"id": "near", "phash": near, "dhash": None, "date": "", "where": "", "note": ""},
        {"id": "far", "phash": far, "dhash": None, "date": "", "where": "", "note": ""},
    ]

    matches = match_known_cases(phash, "", cases)

    assert [item["case"]["id"] for item in matches] == ["near"]
    assert matches[0]["distance"] == 2


