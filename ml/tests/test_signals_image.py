PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


# --------------------------------------------------------------------------
# синтетические изображения
# --------------------------------------------------------------------------


def _chunk(ctype: bytes, payload: bytes) -> bytes:
    crc = zlib.crc32(ctype + payload) & 0xFFFFFFFF
    return struct.pack(">I", len(payload)) + ctype + payload + struct.pack(">I", crc)


def gradient_rows(width: int, height: int, shift: int = 0):
    rows = []
    for y in range(height):
        row = bytearray()
        for x in range(width):
            value = (x * 53 + y * 29 + shift) % 256
            row += bytes((value, value, value))
        rows.append(bytes(row))
    return rows


def checker_rows(width: int, height: int):
    rows = []
    for y in range(height):
        row = bytearray()
        for x in range(width):
            value = 255 if (x + y) % 2 else 0
            row += bytes((value, value, value))
        rows.append(bytes(row))
    return rows


def png(texts=None, width: int = 16, height: int = 16, rows=None, extra=()) -> bytes:
    """PNG 8 бит / RGB: tEXt-чанки + необязательные дополнительные чанки."""
    if rows is None:
        rows = gradient_rows(width, height)
    raw = b"".join(b"\x00" + row for row in rows)
    out = PNG_SIGNATURE
    out += _chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    for ctype, payload in extra:
        out += _chunk(ctype, payload)
    for key, value in (texts or {}).items():
        out += _chunk(b"tEXt", key + b"\x00" + value)
    out += _chunk(b"IDAT", zlib.compress(raw))
    out += _chunk(b"IEND", b"")
    return out


def build_tiff(tags) -> bytes:
    """Big-endian TIFF/Exif IFD c ASCII-тегами (значение → по смещению)."""
    entries = sorted(tags.items())
    ifd_size = 2 + 12 * len(entries) + 4
    data_offset = 8 + ifd_size
    ifd = struct.pack(">H", len(entries))
    blob = b""
    for tag, value in entries:
        encoded = value.encode("utf-8") + b"\x00"
        if len(encoded) <= 4:
            ifd += struct.pack(">HHI", tag, 2, len(encoded)) + encoded.ljust(4, b"\x00")
        else:
            ifd += struct.pack(">HHII", tag, 2, len(encoded), data_offset + len(blob))
            blob += encoded
    ifd += struct.pack(">I", 0)
    return b"MM\x00\x2a" + struct.pack(">I", 8) + ifd + blob


def jpeg_with(*payloads) -> bytes:
    out = b"\xff\xd8"
    for payload in payloads:
        out += b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload
    return out + b"\xff\xd9"


def make_ctx(data, *, text: str = "", options=None, search=None) -> CheckContext:
    return CheckContext(
        check_id="test-image",
        input=CheckInput(type=InputType.image),
        data=data,
        text=text,
        search=search,
        options=dict(options or {}),
    )


class FakeSearch:
    """Мини-провайдер поиска: backend в тестах не нужен."""

    def __init__(self, hits):
        self.hits = list(hits)
        self.queries = []

    async def search(self, query):
        self.queries.append(query)
        return self.hits


