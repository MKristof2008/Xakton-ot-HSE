async def test_metadata_generation_markers():
    data = png(texts={b"Software": b"Generated by AI painter"})
    meta = parse_metadata(data)
    assert meta["format"] == "png"
    assert meta["has_metadata"] is True
    assert meta["text"]["Software"] == "Generated by AI painter"

    result = await MetadataSignal().run(make_ctx(data))
    assert result.id == "metadata"
    assert result.stage == Stage.provenance
    assert result.verdict == Verdict.supports_fake
    assert result.reliability == pytest.approx(0.9)
    assert result.details["generators"]
    assert result.details["generators"][0]["marker"] in ("generated by", "generated with")


async def test_metadata_jpeg_exif_camera_and_date():
    tiff = build_tiff({
        0x010F: "Canon",
        0x0110: "EOS R6",
        0x9003: "2024:05:12 10:30:00",
    })
    data = jpeg_with(b"Exif\x00\x00" + tiff)
    meta = parse_metadata(data)
    assert meta["format"] == "jpeg"
    assert meta["exif"]["Make"] == "Canon"
    assert meta["exif"]["DateTimeOriginal"] == "2024:05:12 10:30:00"

    result = await MetadataSignal().run(make_ctx(data))
    assert result.verdict == Verdict.supports_real
    assert result.reliability == pytest.approx(0.6)
    assert result.details["camera"] == "Canon EOS R6"
    assert result.details["datetime"] == "2024:05:12 10:30:00"


